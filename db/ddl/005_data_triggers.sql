-- ============================================================================
-- Twogether - Audit triggers for data tables
-- Run order: 005 (after 003_sequences.sql)
-- Assigns RSN from sequences and maintains audit/version columns.
-- ============================================================================
SET DEFINE OFF;

CREATE OR REPLACE TRIGGER TG$ACCESS_TAB_TRG1
BEFORE INSERT OR UPDATE ON TG$ACCESS_TAB
FOR EACH ROW
DECLARE
  l_user VARCHAR2(255) := COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER);
BEGIN
  IF INSERTING THEN
    IF :NEW.RSN IS NULL THEN
      :NEW.RSN := TG$ACCESS_SEQ.NEXTVAL;
    END IF;
    :NEW.UUID        := NVL(:NEW.UUID, SYS_GUID());
    :NEW.CREATEDDATE := NVL(:NEW.CREATEDDATE, SYSTIMESTAMP);
    :NEW.CREATEDBY   := NVL(:NEW.CREATEDBY, l_user);
    :NEW.STAMPUSER   := l_user;
    :NEW.STAMPDATE   := NVL(:NEW.STAMPDATE, SYSTIMESTAMP);
    :NEW.VERSIONNO   := 1;
  ELSE
    :NEW.RSN         := :OLD.RSN;
    :NEW.ACCESSCODE  := :OLD.ACCESSCODE;
    :NEW.UUID        := :OLD.UUID;
    :NEW.CREATEDDATE := :OLD.CREATEDDATE;
    :NEW.CREATEDBY   := :OLD.CREATEDBY;
    :NEW.STAMPUSER   := l_user;
    :NEW.STAMPDATE   := SYSTIMESTAMP;
    :NEW.VERSIONNO   := NVL(:OLD.VERSIONNO, 0) + 1;
  END IF;
END;
/

