CREATE INDEX TG$MEMBER_TAB_IX1 ON TG$MEMBER_TAB (ACCESSCODE, EMAIL);
CREATE INDEX TG$LIST_TAB_IX1   ON TG$LIST_TAB   (ACCESSCODE, STATUSCODE, LISTDATE);
CREATE INDEX TG$ITEM_TAB_IX1   ON TG$ITEM_TAB   (ACCESSCODE, STATUSCODE, DUEDATE);
CREATE INDEX TG$ITEM_TAB_IX2   ON TG$ITEM_TAB   (LISTRSN);
CREATE INDEX TG$ITEM_TAB_IX3   ON TG$ITEM_TAB   (ACCESSCODE, PRIORITYCODE, DUEDATE);
CREATE INDEX TG$ITEM_TAB_IX4   ON TG$ITEM_TAB   (ACCESSCODE, REMINDERDATE);
