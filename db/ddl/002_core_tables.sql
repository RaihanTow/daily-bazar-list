  STATUSCODE    VARCHAR2(30)  DEFAULT 'ACTIVE' NOT NULL,
  JOINEDDATE    DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  UUID          RAW(16)       DEFAULT SYS_GUID() NOT NULL,
  STAMPUSER     VARCHAR2(255)                 NOT NULL,
  STAMPDATE     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDDATE   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDBY     VARCHAR2(255)                 NOT NULL,
  VERSIONNO     NUMBER(10)    DEFAULT 1       NOT NULL,
  ISDELETED     CHAR(1)       DEFAULT 'N'     NOT NULL,
  DELETEDDATE   TIMESTAMP WITH TIME ZONE,
  DELETEDBY     VARCHAR2(255),
  CONSTRAINT TG$MEMBER_TAB001_PK  PRIMARY KEY (RSN),
  CONSTRAINT TG$MEMBER_TAB001_UK1 UNIQUE (ACCESSCODE, MEMBERCODE),
  CONSTRAINT TG$MEMBER_TAB001_UK2 UNIQUE (ACCESSCODE, USERNAME),
  CONSTRAINT TG$MEMBER_TAB001_UK3 UNIQUE (UUID),
  CONSTRAINT TG$MEMBER_TAB001_FK1 FOREIGN KEY (ACCESSCODE)
    REFERENCES TG$ACCESS_TAB001 (ACCESSCODE),
  CONSTRAINT TG$MEMBER_TAB001_FK2 FOREIGN KEY (ROLETYPE_CODE)
