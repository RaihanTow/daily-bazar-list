-- ----------------------------------------------------------------------------
-- TG$ITEM_TAB - wish-list item with priority and due date
-- ----------------------------------------------------------------------------
CREATE TABLE TG$ITEM_TAB (
  RSN           NUMBER(19)                    NOT NULL,
  ACCESSCODE    VARCHAR2(30)                  NOT NULL,
  ITEMCODE      VARCHAR2(30)                  NOT NULL,
  LISTRSN       NUMBER(19)                    NOT NULL,
  ITEMNAME      VARCHAR2(200)                 NOT NULL,
  ITEMDESC      VARCHAR2(4000),
  CATEGORYCODE  NUMBER(19),
  PRIORITYCODE  NUMBER(19)                    NOT NULL,
  STATUSCODE    NUMBER(19)                    NOT NULL,
  DUEDATE       DATE,
  QUANTITY      NUMBER(12,3)  DEFAULT 1       NOT NULL,
  UOMCODE       NUMBER(19)                    NOT NULL,
  ESTCOST       NUMBER(12,2),
  CURRENCYCODE  VARCHAR2(3)   DEFAULT 'USD'   NOT NULL,
  ASSIGNEDUSER  VARCHAR2(255),
  ISREMINDER    CHAR(1)       DEFAULT 'N'     NOT NULL,
  REMINDERDATE  DATE,
  COMPLETEDDATE TIMESTAMP WITH TIME ZONE,
  COMPLETEDBY   VARCHAR2(255),
  UUID          RAW(16)       DEFAULT SYS_GUID() NOT NULL,
  STAMPUSER     VARCHAR2(255)                 NOT NULL,
  STAMPDATE     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  STAMPSESSION  VARCHAR2(4000) DEFAULT SYS_CONTEXT('APEX$SESSION','APP_SESSION'),
  CREATEDDATE   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDBY     VARCHAR2(255)                 NOT NULL,
  CREATESESSION VARCHAR2(4000) DEFAULT SYS_CONTEXT('APEX$SESSION','APP_SESSION'),
  APPID         VARCHAR2(100)  DEFAULT SYS_CONTEXT('APEX$SESSION','APP_ID'),
  VERSIONNO     NUMBER(10)    DEFAULT 1       NOT NULL,
  ISDELETED     CHAR(1)       DEFAULT 'N'     NOT NULL,
  DELETEDDATE   TIMESTAMP WITH TIME ZONE,
  DELETEDBY     VARCHAR2(255),
  CONSTRAINT TG$ITEM_TAB_PK  PRIMARY KEY (RSN),
  CONSTRAINT TG$ITEM_TAB_UK1 UNIQUE (ACCESSCODE, ITEMCODE),
  CONSTRAINT TG$ITEM_TAB_UK2 UNIQUE (UUID),
  CONSTRAINT TG$ITEM_TAB_FK1 FOREIGN KEY (ACCESSCODE)
    REFERENCES TG$ACCESS_TAB (ACCESSCODE),
  CONSTRAINT TG$ITEM_TAB_FK2 FOREIGN KEY (LISTRSN)
    REFERENCES TG$LIST_TAB (RSN),
  CONSTRAINT TG$ITEM_TAB_FK3 FOREIGN KEY (CATEGORYCODE)
    REFERENCES TG$VALID_CATEGORY_TAB (CATEGORYCODE),
  CONSTRAINT TG$ITEM_TAB_FK4 FOREIGN KEY (PRIORITYCODE)
    REFERENCES TG$VALID_PRIORITY_TAB (PRIORITYCODE),
  CONSTRAINT TG$ITEM_TAB_FK5 FOREIGN KEY (STATUSCODE)
    REFERENCES TG$VALID_STATUS_TAB (STATUSCODE),
  CONSTRAINT TG$ITEM_TAB_FK6 FOREIGN KEY (UOMCODE)
    REFERENCES TG$VALID_UOM_TAB (UOMCODE),
  CONSTRAINT TG$ITEM_TAB_CK1 CHECK (QUANTITY > 0),
  CONSTRAINT TG$ITEM_TAB_CK2 CHECK (ISREMINDER IN ('Y','N')),
  CONSTRAINT TG$ITEM_TAB_CK3 CHECK (ISDELETED  IN ('Y','N'))
);

-- ----------------------------------------------------------------------------
-- TG$ITEM_HISTORY_TAB - item change history
-- ----------------------------------------------------------------------------
CREATE TABLE TG$ITEM_HISTORY_TAB (
  RSN           NUMBER(19)                    NOT NULL,
  ACCESSCODE    VARCHAR2(30)                  NOT NULL,
  ITEMRSN       NUMBER(19)                    NOT NULL,
  ACTIONCODE    VARCHAR2(20)                  NOT NULL,
  CHANGEDBY     VARCHAR2(255)                 NOT NULL,
  CHANGEDDATE   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHANGEDATA    CLOB,
  UUID          RAW(16)       DEFAULT SYS_GUID() NOT NULL,
  STAMPUSER     VARCHAR2(255)                 NOT NULL,
  STAMPDATE     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  STAMPSESSION  VARCHAR2(4000) DEFAULT SYS_CONTEXT('APEX$SESSION','APP_SESSION'),
  CREATEDDATE   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDBY     VARCHAR2(255)                 NOT NULL,
  CREATESESSION VARCHAR2(4000) DEFAULT SYS_CONTEXT('APEX$SESSION','APP_SESSION'),
  APPID         VARCHAR2(100)  DEFAULT SYS_CONTEXT('APEX$SESSION','APP_ID'),
  VERSIONNO     NUMBER(10)    DEFAULT 1       NOT NULL,
  ISDELETED     CHAR(1)       DEFAULT 'N'     NOT NULL,
  CONSTRAINT TG$ITEM_HISTORY_TAB_PK  PRIMARY KEY (RSN),
  CONSTRAINT TG$ITEM_HISTORY_TAB_UK1 UNIQUE (UUID),
  CONSTRAINT TG$ITEM_HISTORY_TAB_FK1 FOREIGN KEY (ACCESSCODE)
    REFERENCES TG$ACCESS_TAB (ACCESSCODE),
  CONSTRAINT TG$ITEM_HISTORY_TAB_FK2 FOREIGN KEY (ITEMRSN)
    REFERENCES TG$ITEM_TAB (RSN),
  CONSTRAINT TG$ITEM_HISTORY_TAB_CK1 CHECK (ACTIONCODE IN ('INSERT','UPDATE','DELETE')),
  CONSTRAINT TG$ITEM_HISTORY_TAB_CK2 CHECK (ISDELETED  IN ('Y','N'))
);

-- ----------------------------------------------------------------------------
-- Supporting indexes
