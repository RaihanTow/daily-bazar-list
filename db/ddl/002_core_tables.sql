  CONSTRAINT TG$MEMBER_TAB001_FK3 FOREIGN KEY (STATUSCODE)
    REFERENCES TG$STATUS_TAB001 (CODE),
  CONSTRAINT TG$MEMBER_TAB001_CK1 CHECK (ISDELETED IN ('Y','N'))
);

