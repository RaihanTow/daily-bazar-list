-- ----------------------------------------------------------------------------
-- TG$ITEM_TAB001 - wish-list item with priority and due date
-- ----------------------------------------------------------------------------
CREATE TABLE TG$ITEM_TAB001 (
  RSN           NUMBER(19)                    NOT NULL,
  ACCESSCODE    VARCHAR2(30)                  NOT NULL,
  ITEMCODE      VARCHAR2(30)                  NOT NULL,
  LISTRSN       NUMBER(19)                    NOT NULL,
  ITEMNAME      VARCHAR2(200)                 NOT NULL,
  ITEMDESC      VARCHAR2(4000),
  CATEGORYCODE  VARCHAR2(30),
  PRIORITYCODE  VARCHAR2(30)  DEFAULT 'MEDIUM' NOT NULL,
  STATUSCODE    VARCHAR2(30)  DEFAULT 'ACTIVE' NOT NULL,
  DUEDATE       DATE,
  QUANTITY      NUMBER(12,3)  DEFAULT 1       NOT NULL,
  UOMCODE       VARCHAR2(30)  DEFAULT 'PCS'   NOT NULL,
  ESTCOST       NUMBER(12,2),
  CURRENCYCODE  VARCHAR2(3)   DEFAULT 'USD'   NOT NULL,
  ASSIGNEDUSER  VARCHAR2(255),
  ISREMINDER    CHAR(1)       DEFAULT 'N'     NOT NULL,
  REMINDERDATE  DATE,
  COMPLETEDDATE TIMESTAMP WITH TIME ZONE,
  COMPLETEDBY   VARCHAR2(255),
  UUID          RAW(16)       DEFAULT SYS_GUID() NOT NULL,
  STAMPUSER     VARCHAR2(255)                 NOT NULL,
  STAMPDATE     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDDATE   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDBY     VARCHAR2(255)                 NOT NULL,
  VERSIONNO     NUMBER(10)    DEFAULT 1       NOT NULL,
  ISDELETED     CHAR(1)       DEFAULT 'N'     NOT NULL,
  DELETEDDATE   TIMESTAMP WITH TIME ZONE,
  DELETEDBY     VARCHAR2(255),
  CONSTRAINT TG$ITEM_TAB001_PK  PRIMARY KEY (RSN),
  CONSTRAINT TG$ITEM_TAB001_UK1 UNIQUE (ACCESSCODE, ITEMCODE),
  CONSTRAINT TG$ITEM_TAB001_UK2 UNIQUE (UUID),
  CONSTRAINT TG$ITEM_TAB001_FK1 FOREIGN KEY (ACCESSCODE)
    REFERENCES TG$ACCESS_TAB001 (ACCESSCODE),
  CONSTRAINT TG$ITEM_TAB001_FK2 FOREIGN KEY (LISTRSN)
    REFERENCES TG$LIST_TAB001 (RSN),
  CONSTRAINT TG$ITEM_TAB001_FK3 FOREIGN KEY (CATEGORYCODE)
    REFERENCES TG$CATEGORY_TAB001 (CODE),
  CONSTRAINT TG$ITEM_TAB001_FK4 FOREIGN KEY (PRIORITYCODE)
    REFERENCES TG$PRIORITY_TAB001 (CODE),
  CONSTRAINT TG$ITEM_TAB001_FK5 FOREIGN KEY (STATUSCODE)
    REFERENCES TG$STATUS_TAB001 (CODE),
  CONSTRAINT TG$ITEM_TAB001_FK6 FOREIGN KEY (UOMCODE)
    REFERENCES TG$UOM_TAB001 (CODE),
  CONSTRAINT TG$ITEM_TAB001_CK1 CHECK (QUANTITY > 0),
  CONSTRAINT TG$ITEM_TAB001_CK2 CHECK (ISREMINDER IN ('Y','N')),
  CONSTRAINT TG$ITEM_TAB001_CK3 CHECK (ISDELETED  IN ('Y','N'))
);

-- ----------------------------------------------------------------------------
-- TG$ITEM_HISTORY_TAB001 - item change history
-- ----------------------------------------------------------------------------
CREATE TABLE TG$ITEM_HISTORY_TAB001 (
  RSN           NUMBER(19)                    NOT NULL,
  ACCESSCODE    VARCHAR2(30)                  NOT NULL,
  ITEMRSN       NUMBER(19)                    NOT NULL,
  ACTIONCODE    VARCHAR2(20)                  NOT NULL,
  CHANGEDBY     VARCHAR2(255)                 NOT NULL,
  CHANGEDDATE   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHANGEDATA    CLOB,
  UUID          RAW(16)       DEFAULT SYS_GUID() NOT NULL,
  STAMPUSER     VARCHAR2(255)                 NOT NULL,
  STAMPDATE     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDDATE   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATEDBY     VARCHAR2(255)                 NOT NULL,
  VERSIONNO     NUMBER(10)    DEFAULT 1       NOT NULL,
  ISDELETED     CHAR(1)       DEFAULT 'N'     NOT NULL,
  CONSTRAINT TG$ITEM_HISTORY_TAB001_PK  PRIMARY KEY (RSN),
  CONSTRAINT TG$ITEM_HISTORY_TAB001_UK1 UNIQUE (UUID),
  CONSTRAINT TG$ITEM_HISTORY_TAB001_FK1 FOREIGN KEY (ACCESSCODE)
    REFERENCES TG$ACCESS_TAB001 (ACCESSCODE),
  CONSTRAINT TG$ITEM_HISTORY_TAB001_FK2 FOREIGN KEY (ITEMRSN)
    REFERENCES TG$ITEM_TAB001 (RSN),
  CONSTRAINT TG$ITEM_HISTORY_TAB001_CK1 CHECK (ACTIONCODE IN ('INSERT','UPDATE','DELETE')),
  CONSTRAINT TG$ITEM_HISTORY_TAB001_CK2 CHECK (ISDELETED  IN ('Y','N'))
);

