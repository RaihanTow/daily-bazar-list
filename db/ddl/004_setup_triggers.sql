SET DEFINE OFF;

CREATE OR REPLACE TRIGGER TG$STATUS_TAB001_TRG1
BEFORE INSERT OR UPDATE ON TG$STATUS_TAB001
FOR EACH ROW
DECLARE
  l_user VARCHAR2(255) := COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER);
BEGIN
  IF INSERTING THEN
    :NEW.CREATEDDATE := NVL(:NEW.CREATEDDATE, SYSTIMESTAMP);
    :NEW.CREATEDBY   := NVL(:NEW.CREATEDBY, l_user);
    :NEW.STAMPUSER   := l_user;
    :NEW.STAMPDATE   := NVL(:NEW.STAMPDATE, SYSTIMESTAMP);
    :NEW.VERSIONNO   := 1;
  ELSE
    :NEW.CODE        := :OLD.CODE;
    :NEW.CREATEDDATE := :OLD.CREATEDDATE;
    :NEW.CREATEDBY   := :OLD.CREATEDBY;
    :NEW.STAMPUSER   := l_user;
    :NEW.STAMPDATE   := SYSTIMESTAMP;
    :NEW.VERSIONNO   := NVL(:OLD.VERSIONNO, 0) + 1;
  END IF;
END;
/

