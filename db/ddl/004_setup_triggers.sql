-- ============================================================================
-- Twogether - Audit triggers for setup tables
-- Run order: 004 (after 003_sequences.sql)
-- Assigns numeric <ENTITY>CODE from TG$VALID_<ENTITY>_SEQ and maintains
-- audit/version columns.
-- ============================================================================
SET DEFINE OFF;

CREATE OR REPLACE TRIGGER TG$VALID_STATUS_TAB_TRG1
BEFORE INSERT OR UPDATE ON TG$VALID_STATUS_TAB
FOR EACH ROW
DECLARE
  l_user VARCHAR2(255) := COALESCE(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER);
BEGIN
  IF INSERTING THEN
    IF :NEW.STATUSCODE IS NULL THEN
      :NEW.STATUSCODE := TG$VALID_STATUS_SEQ.NEXTVAL;
    END IF;
    :NEW.UUID        := NVL(:NEW.UUID, SYS_GUID());
    :NEW.CREATEDDATE := NVL(:NEW.CREATEDDATE, SYSTIMESTAMP);
    :NEW.CREATEDBY   := NVL(:NEW.CREATEDBY, l_user);
    :NEW.STAMPUSER   := l_user;
    :NEW.STAMPDATE   := NVL(:NEW.STAMPDATE, SYSTIMESTAMP);
    :NEW.VERSIONNO   := 1;
  ELSE
    :NEW.STATUSCODE  := :OLD.STATUSCODE;
    :NEW.UUID        := :OLD.UUID;
    :NEW.ACCESSCODE  := :OLD.ACCESSCODE;
    :NEW.CREATEDDATE := :OLD.CREATEDDATE;
    :NEW.CREATEDBY   := :OLD.CREATEDBY;
    :NEW.STAMPUSER   := l_user;
    :NEW.STAMPDATE   := SYSTIMESTAMP;
    :NEW.VERSIONNO   := NVL(:OLD.VERSIONNO, 0) + 1;
  END IF;
END;
/

