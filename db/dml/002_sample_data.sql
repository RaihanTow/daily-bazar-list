-- ============================================================================
-- Twogether - Sample demo data (idempotent MERGE)
-- Run order: dml/002 (after dml/001_setup_data.sql)
-- Demo household: ACC-DEMO-001
-- ============================================================================
SET DEFINE OFF;

-- Household ------------------------------------------------------------------
MERGE INTO TG$ACCESS_TAB001 t
USING (
  SELECT 'ACC-DEMO-001'  ACCESSCODE,
         'Demo Household' ACCESSNAME,
         'DEMO_USER'      OWNERUSER,
         'INV-DEMO-001'   INVITECODE,
         'en'             LOCALE,
         'UTC'            TIMEZONE,
         'USD'            CURRENCYCODE,
         'ACTIVE'         STATUSCODE
  FROM dual
) s
ON (t.ACCESSCODE = s.ACCESSCODE)
WHEN MATCHED THEN UPDATE SET
  t.ACCESSNAME = s.ACCESSNAME, t.OWNERUSER = s.OWNERUSER,
  t.INVITECODE = s.INVITECODE, t.LOCALE = s.LOCALE,
  t.TIMEZONE = s.TIMEZONE, t.CURRENCYCODE = s.CURRENCYCODE,
  t.STATUSCODE = s.STATUSCODE
WHEN NOT MATCHED THEN INSERT
  (ACCESSCODE, ACCESSNAME, OWNERUSER, INVITECODE, LOCALE, TIMEZONE, CURRENCYCODE, STATUSCODE)
VALUES
  (s.ACCESSCODE, s.ACCESSNAME, s.OWNERUSER, s.INVITECODE, s.LOCALE, s.TIMEZONE, s.CURRENCYCODE, s.STATUSCODE);

-- Members --------------------------------------------------------------------
MERGE INTO TG$MEMBER_TAB001 t
USING (
  SELECT 'ACC-DEMO-001' ACCESSCODE, 'MEM-DEMO-001' MEMBERCODE, 'DEMO_USER'    USERNAME,
         'Demo User'    DISPLAYNAME, 'demo@example.com'    EMAIL, 'OWNER'  ROLETYPE_CODE,
         'ACTIVE'       STATUSCODE, TRUNC(SYSDATE)        JOINEDDATE FROM dual UNION ALL
  SELECT 'ACC-DEMO-001' ACCESSCODE, 'MEM-DEMO-002' MEMBERCODE, 'PARTNER_USER' USERNAME,
         'Partner User' DISPLAYNAME, 'partner@example.com' EMAIL, 'MEMBER' ROLETYPE_CODE,
         'ACTIVE'       STATUSCODE, TRUNC(SYSDATE)        JOINEDDATE FROM dual
) s
ON (t.ACCESSCODE = s.ACCESSCODE AND t.MEMBERCODE = s.MEMBERCODE)
WHEN MATCHED THEN UPDATE SET
  t.USERNAME = s.USERNAME, t.DISPLAYNAME = s.DISPLAYNAME, t.EMAIL = s.EMAIL,
  t.ROLETYPE_CODE = s.ROLETYPE_CODE, t.STATUSCODE = s.STATUSCODE, t.JOINEDDATE = s.JOINEDDATE
WHEN NOT MATCHED THEN INSERT
  (ACCESSCODE, MEMBERCODE, USERNAME, DISPLAYNAME, EMAIL, ROLETYPE_CODE, STATUSCODE, JOINEDDATE)
VALUES
  (s.ACCESSCODE, s.MEMBERCODE, s.USERNAME, s.DISPLAYNAME, s.EMAIL, s.ROLETYPE_CODE, s.STATUSCODE, s.JOINEDDATE);

-- Shopping list --------------------------------------------------------------
MERGE INTO TG$LIST_TAB001 t
USING (
  SELECT 'ACC-DEMO-001'  ACCESSCODE,
         'LIST-DEMO-001' LISTCODE,
         'Weekly Bazar'   LISTNAME,
         'Weekly household shopping' LISTDESC,
         TRUNC(SYSDATE)  LISTDATE,
         'ACTIVE'        STATUSCODE
  FROM dual
) s
ON (t.ACCESSCODE = s.ACCESSCODE AND t.LISTCODE = s.LISTCODE)
WHEN MATCHED THEN UPDATE SET
  t.LISTNAME = s.LISTNAME, t.LISTDESC = s.LISTDESC,
  t.LISTDATE = s.LISTDATE, t.STATUSCODE = s.STATUSCODE
WHEN NOT MATCHED THEN INSERT
  (ACCESSCODE, LISTCODE, LISTNAME, LISTDESC, LISTDATE, STATUSCODE)
VALUES
  (s.ACCESSCODE, s.LISTCODE, s.LISTNAME, s.LISTDESC, s.LISTDATE, s.STATUSCODE);

-- Items ----------------------------------------------------------------------
MERGE INTO TG$ITEM_TAB001 t
USING (
  SELECT 'ACC-DEMO-001' ACCESSCODE, 'ITEM-DEMO-001' ITEMCODE,
         (SELECT RSN FROM TG$LIST_TAB001 WHERE ACCESSCODE = 'ACC-DEMO-001' AND LISTCODE = 'LIST-DEMO-001') LISTRSN,
         'Milk' ITEMNAME, 'Fresh milk' ITEMDESC, 'GROCERY' CATEGORYCODE,
         'HIGH' PRIORITYCODE, 'ACTIVE' STATUSCODE, TRUNC(SYSDATE)+1 DUEDATE,
         2 QUANTITY, 'L' UOMCODE, 3.50 ESTCOST, 'USD' CURRENCYCODE,
         'PARTNER_USER' ASSIGNEDUSER, 'N' ISREMINDER, CAST(NULL AS DATE) REMINDERDATE FROM dual UNION ALL
  SELECT 'ACC-DEMO-001', 'ITEM-DEMO-002',
         (SELECT RSN FROM TG$LIST_TAB001 WHERE ACCESSCODE = 'ACC-DEMO-001' AND LISTCODE = 'LIST-DEMO-001'),
         'Rice', 'Basmati rice', 'GROCERY',
         'MEDIUM', 'ACTIVE', TRUNC(SYSDATE)+2,
         5, 'KG', 12.00, 'USD',
         'DEMO_USER', 'N', CAST(NULL AS DATE) FROM dual UNION ALL
  SELECT 'ACC-DEMO-001', 'ITEM-DEMO-003',
         (SELECT RSN FROM TG$LIST_TAB001 WHERE ACCESSCODE = 'ACC-DEMO-001' AND LISTCODE = 'LIST-DEMO-001'),
         'Dish soap', 'Lemon dish soap', 'HOUSEHOLD',
         'LOW', 'ACTIVE', TRUNC(SYSDATE)+5,
         1, 'PCS', 2.25, 'USD',
         CAST(NULL AS VARCHAR2(255)), 'N', CAST(NULL AS DATE) FROM dual UNION ALL
  SELECT 'ACC-DEMO-001', 'ITEM-DEMO-004',
         (SELECT RSN FROM TG$LIST_TAB001 WHERE ACCESSCODE = 'ACC-DEMO-001' AND LISTCODE = 'LIST-DEMO-001'),
         'Toothpaste', 'Fluoride toothpaste', 'PERSONAL',
         'MEDIUM', 'ACTIVE', TRUNC(SYSDATE)+3,
         2, 'PCS', 4.00, 'USD',
         'PARTNER_USER', 'Y', TRUNC(SYSDATE)+3 FROM dual UNION ALL
  SELECT 'ACC-DEMO-001', 'ITEM-DEMO-005',
         (SELECT RSN FROM TG$LIST_TAB001 WHERE ACCESSCODE = 'ACC-DEMO-001' AND LISTCODE = 'LIST-DEMO-001'),
         'Pain relief', 'Paracetamol 500mg', 'MEDICAL',
         'URGENT', 'ACTIVE', TRUNC(SYSDATE),
         1, 'BOX', 5.50, 'USD',
         'DEMO_USER', 'Y', TRUNC(SYSDATE) FROM dual UNION ALL
  SELECT 'ACC-DEMO-001', 'ITEM-DEMO-006',
         (SELECT RSN FROM TG$LIST_TAB001 WHERE ACCESSCODE = 'ACC-DEMO-001' AND LISTCODE = 'LIST-DEMO-001'),
         'Bread', 'Whole wheat bread', 'GROCERY',
         'MEDIUM', 'DONE', TRUNC(SYSDATE),
         1, 'PCS', 2.00, 'USD',
         'PARTNER_USER', 'N', CAST(NULL AS DATE) FROM dual
) s
ON (t.ACCESSCODE = s.ACCESSCODE AND t.ITEMCODE = s.ITEMCODE)
WHEN MATCHED THEN UPDATE SET
  t.LISTRSN = s.LISTRSN, t.ITEMNAME = s.ITEMNAME, t.ITEMDESC = s.ITEMDESC,
  t.CATEGORYCODE = s.CATEGORYCODE, t.PRIORITYCODE = s.PRIORITYCODE,
  t.STATUSCODE = s.STATUSCODE, t.DUEDATE = s.DUEDATE, t.QUANTITY = s.QUANTITY,
  t.UOMCODE = s.UOMCODE, t.ESTCOST = s.ESTCOST, t.CURRENCYCODE = s.CURRENCYCODE,
  t.ASSIGNEDUSER = s.ASSIGNEDUSER, t.ISREMINDER = s.ISREMINDER, t.REMINDERDATE = s.REMINDERDATE
WHEN NOT MATCHED THEN INSERT
  (ACCESSCODE, ITEMCODE, LISTRSN, ITEMNAME, ITEMDESC, CATEGORYCODE,
   PRIORITYCODE, STATUSCODE, DUEDATE, QUANTITY, UOMCODE, ESTCOST,
   CURRENCYCODE, ASSIGNEDUSER, ISREMINDER, REMINDERDATE)
VALUES
  (s.ACCESSCODE, s.ITEMCODE, s.LISTRSN, s.ITEMNAME, s.ITEMDESC, s.CATEGORYCODE,
   s.PRIORITYCODE, s.STATUSCODE, s.DUEDATE, s.QUANTITY, s.UOMCODE, s.ESTCOST,
   s.CURRENCYCODE, s.ASSIGNEDUSER, s.ISREMINDER, s.REMINDERDATE);

-- Mark the bread item as completed (also writes item history) ----------------
UPDATE TG$ITEM_TAB001
SET    STATUSCODE    = 'DONE',
       COMPLETEDDATE = SYSTIMESTAMP,
       COMPLETEDBY   = 'PARTNER_USER'
WHERE  ACCESSCODE = 'ACC-DEMO-001'
AND    ITEMCODE   = 'ITEM-DEMO-006';

COMMIT;
