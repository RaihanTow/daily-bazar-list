SET DEFINE OFF;

-- Statuses -------------------------------------------------------------------
MERGE INTO TG$STATUS_TAB001 t
USING (
  SELECT 'ACTIVE'    CODE, 'Active'    DISPLAYNAME, 'Item is still needed'     DESCRIPTION, 10 SORTNO, 'Y' ISACTIVE, 'Y' ISDEFAULT FROM dual UNION ALL
  SELECT 'DONE'      CODE, 'Done'      DISPLAYNAME, 'Item has been bought'     DESCRIPTION, 20 SORTNO, 'Y' ISACTIVE, 'N' ISDEFAULT FROM dual UNION ALL
  SELECT 'CANCELLED' CODE, 'Cancelled' DISPLAYNAME, 'Item is no longer needed' DESCRIPTION, 30 SORTNO, 'Y' ISACTIVE, 'N' ISDEFAULT FROM dual UNION ALL
  SELECT 'ARCHIVED'  CODE, 'Archived'  DISPLAYNAME, 'Item moved to archive'    DESCRIPTION, 40 SORTNO, 'Y' ISACTIVE, 'N' ISDEFAULT FROM dual
) s
ON (t.CODE = s.CODE)
WHEN MATCHED THEN UPDATE SET
  t.DISPLAYNAME = s.DISPLAYNAME, t.DESCRIPTION = s.DESCRIPTION,
  t.SORTNO = s.SORTNO, t.ISACTIVE = s.ISACTIVE, t.ISDEFAULT = s.ISDEFAULT
WHEN NOT MATCHED THEN INSERT
  (CODE, DISPLAYNAME, DESCRIPTION, SORTNO, ISACTIVE, ISDEFAULT)
VALUES
  (s.CODE, s.DISPLAYNAME, s.DESCRIPTION, s.SORTNO, s.ISACTIVE, s.ISDEFAULT);

